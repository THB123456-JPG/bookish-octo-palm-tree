"""各机器人类型 —— 一个类型一个文件夹

    kefu/     客服机器人
    usdt/     USDT 助手
    shop/     商城机器人
    ledger/   记账机器人

★ 分文件夹的目的：**改一个类型，不碰到别的类型**。
  记账出问题，只看 `runners/ledger/` 就够了，不会路过商城的代码。

文件夹名 = `bot['type']` 的值（见 manager.RUNNERS），两边必须一致。

──────────────────────────────────────────────
改这里的东西之前，先看三条规矩
──────────────────────────────────────────────

1. **类型字符串不许改。** `'kefu'` / `'usdt'` / `'shop'` / `'ledger'` 是**数据**，
   已经存在 `bots.json` 和服务器上了。改了这几个词，存量机器人全部认不出来。

2. **`runners/<类型>/` 之外的共享东西改起来要小心：**

   | 文件 | 谁在用 |
   |---|---|
   | `core.py` | 所有类型（框架） |
   | `tron.py` | usdt + shop（链上查询、地址编解码、汇率） |
   | `panel.py` | 所有类型（面板路由表） |
   | `archive.py` | ledger（群消息记录） |

   特别是 `tron.py` —— 它以前塞在 `usdt.py` 里，导致「动 USDT 助手 = 有把商城搞挂的风险」，
   2026-09-29 才拆出来。

3. **包内部用相对导入**（`from .storage import ...`），
   **引用外面的共享模块用绝对导入**（`from core import ...`）。

──────────────────────────────────────────────
加一个新机器人类型要改哪些地方
──────────────────────────────────────────────
   1. 建 `runners/<类型>/`，写 `runner.py`（继承 `core.BaseRunner`）+ `__init__.py`
   2. `manager.py` 的 `RUNNERS` 表加一行
   3. 前端 `panel_page.html` 的 `<select id="type">` 和 `TYPE_TABS` 加一项
      （顺序要和 RUNNERS 保持一致）
   4. `TG客服多开版.spec` 的 `hiddenimports` 加上新模块
   5. 如果它有面板接口，在 `panel.py` 路由表登记 → 实现写在自己的 `api.py`
"""
